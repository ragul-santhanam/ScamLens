/**
 * ScamLens Engine & Asset Synchronizer
 * 1. Copies shared analysis rules and engine files from shared/ to app/www/js/engine/
 * 2. Generates browser-compatible rules bundle
 * 3. Synchronizes app/www to root www/ for Capacitor asset packaging
 */
const fs = require('fs');
const path = require('path');

const rootDir = path.resolve(__dirname, '..');
const sharedDir = path.join(rootDir, 'shared');
const appWwwDir = path.join(rootDir, 'app', 'www');
const rootWwwDir = path.join(rootDir, 'www');

function copyRecursiveSync(src, dest) {
  if (!fs.existsSync(src)) return;
  const stats = fs.statSync(src);

  if (stats.isDirectory()) {
    if (!fs.existsSync(dest)) {
      fs.mkdirSync(dest, { recursive: true });
    }
    fs.readdirSync(src).forEach((child) => {
      copyRecursiveSync(path.join(src, child), path.join(dest, child));
    });
  } else {
    fs.copyFileSync(src, dest);
  }
}

console.log('[Sync] Copying shared/ -> app/www/js/engine/...');
const destEngineDir = path.join(appWwwDir, 'js', 'engine');
copyRecursiveSync(sharedDir, destEngineDir);

// Generate synchronous browser rules file
const rulesJsonPath = path.join(sharedDir, 'rules', 'message.json');
if (fs.existsSync(rulesJsonPath)) {
  const rulesData = fs.readFileSync(rulesJsonPath, 'utf8');
  const bundleJs = `/**
 * ScamLens Synchronous Message Rules (Auto-generated by scripts/sync-engine.js)
 */
(function (root) {
  root.ScamLensRules = ${rulesData};
}(typeof self !== 'undefined' ? self : this));
`;
  const destRulesJs = path.join(destEngineDir, 'rules', 'message.rules.js');
  fs.writeFileSync(destRulesJs, bundleJs, 'utf8');
  console.log('[Sync] Generated app/www/js/engine/rules/message.rules.js');
}

// Synchronize app/www to root www for Capacitor build
console.log('[Sync] Mirroring app/www/ -> www/...');
copyRecursiveSync(appWwwDir, rootWwwDir);

// Directly sync to android assets if android project is present
const androidPublicDir = path.join(rootDir, 'android', 'app', 'src', 'main', 'assets', 'public');
if (fs.existsSync(androidPublicDir)) {
  console.log('[Sync] Mirroring app/www/ -> android/app/src/main/assets/public/...');
  copyRecursiveSync(appWwwDir, androidPublicDir);
}

const capConfigSrc = path.join(rootDir, 'capacitor.config.json');
const capConfigAndroidDest = path.join(rootDir, 'android', 'app', 'src', 'main', 'assets', 'capacitor.config.json');
if (fs.existsSync(capConfigSrc) && fs.existsSync(path.dirname(capConfigAndroidDest))) {
  fs.copyFileSync(capConfigSrc, capConfigAndroidDest);
  console.log('[Sync] Updated android/app/src/main/assets/capacitor.config.json');
}

console.log('[Sync] Completed asset synchronization.');
